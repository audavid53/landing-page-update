#!/usr/bin/env node
/**
 * Fetches the 3D illustration set into public/art/3d/.
 *
 * Source: microsoft/fluentui-emoji (MIT). Its "3D" style is genuinely rendered
 * artwork — soft gradients, gloss highlight, cast shadow — which is the look the
 * product design calls for, and the licence lets us redistribute it.
 *
 * The fetched PNGs are committed, so a build never depends on the network. Re-run
 * this only when the manifest changes:
 *
 *     node scripts/fetch-3d-assets.mjs            # fetch anything missing
 *     node scripts/fetch-3d-assets.mjs --force    # re-fetch everything
 *     node scripts/fetch-3d-assets.mjs --report   # resolve paths, write nothing
 *
 * Upstream stores skin-tone-varying emoji under an extra "Default" folder, and
 * there is no listable index over raw.githubusercontent.com, so each name is
 * probed against both layouts.
 */
import { mkdir, writeFile, access } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { MANIFEST } from "./emoji-manifest.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "public", "art", "3d");
const BASE = "https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets";

const force = process.argv.includes("--force");
const reportOnly = process.argv.includes("--report");

/** Upstream's file naming: lowercase, punctuation dropped, spaces to underscores. */
const snake = (name) =>
  name
    .toLowerCase()
    .replace(/[’'â€™]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");

/** Both known layouts, most common first. */
const candidates = (name) => {
  const s = snake(name);
  const dir = encodeURIComponent(name);
  return [
    `${BASE}/${dir}/3D/${s}_3d.png`,
    `${BASE}/${dir}/Default/3D/${s}_default_3d.png`,
  ];
};

const exists = (p) =>
  access(p).then(
    () => true,
    () => false,
  );

async function resolveOne(slug, name) {
  for (const url of candidates(name)) {
    const res = await fetch(url);
    if (res.ok) return { slug, name, url, bytes: Buffer.from(await res.arrayBuffer()) };
  }
  return { slug, name, url: null };
}

/** Bounded concurrency — polite to the CDN, still finishes in seconds. */
async function pool(items, limit, worker) {
  const out = [];
  let cursor = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (cursor < items.length) out.push(await worker(items[cursor++]));
    }),
  );
  return out;
}

const entries = Object.entries(MANIFEST);
await mkdir(OUT_DIR, { recursive: true });

const todo = [];
for (const [slug, name] of entries) {
  if (!force && !reportOnly && (await exists(join(OUT_DIR, `${slug}.png`)))) continue;
  todo.push([slug, name]);
}

if (todo.length === 0) {
  console.log(`All ${entries.length} assets already present in public/art/3d/.`);
  process.exit(0);
}

console.log(`Resolving ${todo.length} of ${entries.length} assets…`);

const results = await pool(todo, 8, ([slug, name]) => resolveOne(slug, name));
const missing = results.filter((r) => !r.url);

if (!reportOnly) {
  await Promise.all(
    results
      .filter((r) => r.url)
      .map((r) => writeFile(join(OUT_DIR, `${r.slug}.png`), r.bytes)),
  );
}

console.log(`  resolved ${results.length - missing.length}`);
if (missing.length) {
  console.error(`\nUnresolved (fix the name in scripts/emoji-manifest.mjs):`);
  for (const m of missing) console.error(`  ${m.slug.padEnd(16)} -> "${m.name}"`);
  process.exit(1);
}
await writeArtNames();
console.log(`\nWrote ${results.length} PNGs to public/art/3d/`);

/**
 * Emits the slug union the UI types against. Generated rather than hand-kept so
 * `<Art3D name="…" />` cannot reference a PNG that was never fetched.
 */
async function writeArtNames() {
  const slugs = Object.keys(MANIFEST).sort();
  const body = `// Generated by scripts/fetch-3d-assets.mjs — do not edit by hand.
// Run \`pnpm assets:3d\` after changing scripts/emoji-manifest.mjs.

/** Every 3D illustration available in public/art/3d/. */
export type Art3DName =
${slugs.map((s) => `  | ${JSON.stringify(s)}`).join("\n")};

export const ART_3D_NAMES: readonly Art3DName[] = [
${slugs.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
];
`;
  await writeFile(join(ROOT, "src", "data", "art-names.ts"), body);
}
